"""Generate a .def for a drop-in replacement of a Jet module.

Every export of the original keeps its name and ordinal. Exports listed in the "implemented" file are taken
from our own code; all others are forwarded to the renamed original (<module>_orig.dll). Moving a symbol from
forwarded to implemented is how a module gets replaced one class at a time.

usage: python gen_def.py <exports.tsv from dump_exports.py> <module name, e.g. Kernel_7c> <implemented.txt> <out.def>
implemented.txt: one mangled name per line, '#' comments allowed. "name=symbol" exports our symbol under the
original name (for compiler-generated members C++ cannot define, e.g. a default constructor closure).
"""
import csv
import sys
from pathlib import Path

exports_tsv, module, implemented_txt, out_def = sys.argv[1:5]
with open(exports_tsv, encoding="utf-8") as f:
    exports = list(csv.DictReader(f, delimiter="\t"))

implemented = set()
aliases = {}
p = Path(implemented_txt)
if p.exists():
    for line in p.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        name, _, target = line.partition("=")
        implemented.add(name)
        if target:
            aliases[name] = target

unknown = implemented - {e["mangled"] for e in exports}
if unknown:
    sys.exit(f"implemented.txt names not exported by the original: {sorted(unknown)[:5]}")

lines = [f"LIBRARY {module}", "EXPORTS"]
pragmas = []
for e in exports:
    name, ordinal = e["mangled"], e["ordinal"]
    is_data = "(" not in e["demangled"] and name.startswith("?")  # vftables, vbtables, statics
    if name in implemented:
        target = f"={aliases[name]}" if name in aliases else ""
        lines.append(f"    {name}{target} @{ordinal}" + (" DATA" if is_data else ""))
    elif name.startswith("?"):
        lines.append(f"    {name}={module}_orig.{name} @{ordinal}")
    else:
        # link.exe (x86) rejects a .def forwarder for an undecorated C name; the /export pragma works
        pragmas.append(f'#pragma comment(linker, "/export:{name}={module}_orig.{name},@{ordinal}")')
Path(out_def).write_text("\n".join(lines) + "\n", encoding="ascii")
Path(out_def).with_name(f"{module}_forwards.cpp").write_text(
    "// generated by gen_def.py: forwarders for undecorated exports\n" + "\n".join(pragmas) + "\n", encoding="ascii")
print(f"{len(exports)} exports: {len(implemented)} implemented, {len(exports) - len(implemented)} forwarded -> {out_def}")
