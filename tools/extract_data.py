"""Generate a C++ header holding a table read from the user's own copy of a game module, at build time.

Some tables in the original modules have no known generating formula (e.g. KernelStandard's StdMath::s_sqrtLUT,
whose 512 entries are tuned rather than plainly rounded). Instead of copying their bytes into our source, the
build reads them from the original DLL of the installed game, the same way the game reads its data files.

usage: python extract_data.py <dll> <rva hex> <count> <u8|u16|u32> <array name> <out.h>
The header defines `<array name>_DATA` as a brace-free, comma-separated list of the values, for use as
`static const unsigned int table[] = { NAME_DATA };`.
"""
import struct
import sys
from pathlib import Path

dll, rva_text, count_text, kind, name, out = sys.argv[1:7]
rva, count = int(rva_text, 16), int(count_text)
size, fmt = {"u8": (1, "B"), "u16": (2, "H"), "u32": (4, "I")}[kind]

data = Path(dll).read_bytes()
pe = struct.unpack_from("<I", data, 0x3C)[0]
if data[pe:pe + 4] != b"PE\0\0":
    sys.exit(f"{dll}: not a PE file")
sections = struct.unpack_from("<H", data, pe + 6)[0]
opt_size = struct.unpack_from("<H", data, pe + 20)[0]
table = pe + 24 + opt_size
for i in range(sections):
    s = table + i * 40
    vsize, vaddr, rawsize, rawptr = struct.unpack_from("<IIII", data, s + 8)
    if vaddr <= rva and rva + count * size <= vaddr + max(vsize, rawsize):
        offset = rawptr + (rva - vaddr)
        break
else:
    sys.exit(f"{dll}: RVA {rva:#x} is not inside a section")

values = struct.unpack_from(f"<{count}{fmt}", data, offset)
width = size * 2
lines = [", ".join(f"0x{v:0{width}x}" for v in values[i:i + 8]) for i in range(0, count, 8)]
Path(out).parent.mkdir(parents=True, exist_ok=True)
Path(out).write_text(
    f"// generated by extract_data.py from {Path(dll).name} RVA {rva:#x}, {count} x {kind}; do not commit\n"
    f"#define {name}_DATA \\\n    " + ", \\\n    ".join(lines) + "\n",
    encoding="ascii")
print(f"{out}: {count} values from {Path(dll).name} at file offset {offset:#x}")
