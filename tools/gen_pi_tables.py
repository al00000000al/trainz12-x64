"""Generate the Blowfish initial tables (18 P words + 4x256 S words) from the hex digits of pi.

They are the fractional hex digits of pi, so no data needs to be copied from any binary. With a DLL path the
script also checks the result against the tables inside it (Kernel_7c.dll: P at RVA 0x18478, S at 0x184c0).

usage: python gen_pi_tables.py <out header> [Kernel_7c.dll]
"""
import sys

WORDS = 18 + 4 * 256
DIGITS = WORDS * 8 + 16  # hex digits, plus guard digits


def arctan_inv(x, one):
    # arctan(1/x) * one, by the Taylor series in integers
    total = term = one // x
    x2, n, sign = x * x, 1, 1
    while term:
        term //= x2
        n += 2
        sign = -sign
        total += sign * (term // n)
    return total


one = 16 ** (DIGITS + 10)
pi = 4 * (4 * arctan_inv(5, one) - arctan_inv(239, one))  # Machin
frac = pi - 3 * one
digits = format(frac // 16 ** 10, "x").rjust(DIGITS, "0")
words = [int(digits[i * 8:i * 8 + 8], 16) for i in range(WORDS)]
assert words[0] == 0x243F6A88 and words[17] == 0x8979FB1B and words[18] == 0xD1310BA6 and words[-1] == 0x3AC372E6

if len(sys.argv) > 2:
    import struct
    import pefile
    pe = pefile.PE(sys.argv[2])
    p = struct.unpack("<18I", pe.get_data(0x18478, 72))
    s = struct.unpack("<1024I", pe.get_data(0x184C0, 4096))
    assert list(p) + list(s) == words, "tables in the DLL differ from pi"
    print("checked against", sys.argv[2])

lines = ["// Generated by tools/gen_pi_tables.py: Blowfish initial tables, the fractional hex digits of pi.",
         "#pragma once", "", "namespace Jet::BlowfishPi {", "",
         "inline constexpr unsigned int P[18] = {"]
lines += ["    " + ", ".join(f"0x{w:08X}" for w in words[i:i + 6]) + "," for i in range(0, 18, 6)]
lines += ["};", "", "inline constexpr unsigned int S[4][256] = {"]
for b in range(4):
    box = words[18 + 256 * b:18 + 256 * (b + 1)]
    lines.append("    {")
    lines += ["        " + ", ".join(f"0x{w:08X}" for w in box[i:i + 6]) + "," for i in range(0, 256, 6)]
    lines.append("    },")
lines += ["};", "", "}  // namespace Jet::BlowfishPi", ""]
open(sys.argv[1], "w", encoding="ascii").write("\n".join(lines))
print(f"{WORDS} words -> {sys.argv[1]}")
